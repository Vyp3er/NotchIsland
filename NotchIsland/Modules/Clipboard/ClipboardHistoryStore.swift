import AppKit
import Combine
import CryptoKit
import UniformTypeIdentifiers

/// Verlauf der Zwischenablage (Polling von `changeCount`), nur lokal gespeichert.
@MainActor
final class ClipboardHistoryStore: ObservableObject {
    @Published private(set) var items: [ClipboardItem] = []
    /// Zuletzt zurückkopierter Eintrag (für die "Kopiert"-Rückmeldung).
    @Published private(set) var lastCopiedID: UUID?

    private let settings: AppSettings
    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private var feedbackReset: DispatchWorkItem?
    private var cancellables = Set<AnyCancellable>()

    /// Typen, die Passwortmanager & Co. setzen, damit Verläufe sie ignorieren (nspasteboard.org).
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
    ]

    /// Zusätzlich: Inhalte direkt aus Passwort-Apps nie speichern.
    private static let ignoredSources: Set<String> = [
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
        "com.apple.keychainaccess",
        "com.apple.Passwords",
        "in.sinew.Enpass-Desktop",
        "com.dashlane.dashlanephonefinal",
    ]

    private static let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")
    private static let maxTextLength = 100_000

    init(settings: AppSettings) {
        self.settings = settings
        lastChangeCount = pasteboard.changeCount
        load()
        settings.$clipboardLimit
            .dropFirst()
            .sink { [weak self] _ in
                DispatchQueue.main.async {
                    self?.enforceLimit()
                    self?.persist()
                }
            }
            .store(in: &cancellables)
    }

    // MARK: - Überwachung

    func setMonitoring(_ enabled: Bool) {
        if enabled {
            guard timer == nil else { return }
            // Was vor dem Start kopiert wurde, nicht nachträglich übernehmen.
            lastChangeCount = pasteboard.changeCount
            let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
                MainActor.assumeIsolated { self?.poll() }
            }
            timer.tolerance = 0.2
            RunLoop.main.add(timer, forMode: .common)
            self.timer = timer
        } else {
            timer?.invalidate()
            timer = nil
        }
    }

    private func poll() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount
        capture()
    }

    private func capture() {
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }
        let source = pasteboard.string(forType: Self.sourceType)
            ?? NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let source, Self.ignoredSources.contains(source) { return }

        // 1. Kopierte Dateien
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let paths = urls.map(\.path)
            insert(kind: .files, text: nil, imageFileName: nil, filePaths: paths, source: source,
                   fingerprint: "f:" + paths.joined(separator: "\n"))
            return
        }

        // 2. Text oder Link
        if let string = pasteboard.string(forType: .string),
           !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let text = String(string.prefix(Self.maxTextLength))
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            let isLink = !trimmed.contains(where: \.isWhitespace)
                && URL(string: trimmed).map { ["http", "https"].contains($0.scheme?.lowercased() ?? "") && $0.host != nil } == true
            insert(kind: isLink ? .link : .text, text: isLink ? trimmed : text, imageFileName: nil, filePaths: nil,
                   source: source, fingerprint: "t:" + (isLink ? trimmed : text))
            return
        }

        // 3. Bild
        if let data = imageData() {
            let digest = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
            let fingerprint = "i:" + digest
            if items.contains(where: { $0.fingerprint == fingerprint }) {
                insert(kind: .image, text: nil, imageFileName: nil, filePaths: nil, source: source, fingerprint: fingerprint)
                return
            }
            let fileName = "\(digest.prefix(24)).png"
            let url = AppPaths.clipboardImagesDirectory.appendingPathComponent(fileName)
            do {
                try data.write(to: url, options: .atomic)
                insert(kind: .image, text: nil, imageFileName: fileName, filePaths: nil, source: source, fingerprint: fingerprint)
            } catch {
                Log.clipboard.error("Saving clipboard image failed: \(error.localizedDescription, privacy: .public)")
            }
        }
    }

    /// PNG-Daten des Bildes in der Zwischenablage.
    private func imageData() -> Data? {
        if let png = pasteboard.data(forType: .png) { return png }
        guard pasteboard.canReadObject(forClasses: [NSImage.self], options: nil),
              let image = NSImage(pasteboard: pasteboard) else { return nil }
        return image.pngData()
    }

    private func insert(kind: ClipboardItem.Kind, text: String?, imageFileName: String?, filePaths: [String]?,
                        source: String?, fingerprint: String) {
        // Doppelte Einträge nach oben holen statt neu anzulegen.
        if let index = items.firstIndex(where: { $0.fingerprint == fingerprint }) {
            var existing = items.remove(at: index)
            existing.date = Date()
            items.insert(existing, at: 0)
        } else {
            let item = ClipboardItem(
                id: UUID(),
                kind: kind,
                text: text,
                imageFileName: imageFileName,
                filePaths: filePaths,
                isPinned: false,
                date: Date(),
                sourceBundleID: source,
                fingerprint: fingerprint
            )
            items.insert(item, at: 0)
        }
        enforceLimit()
        persist()
    }

    private func enforceLimit() {
        let limit = max(5, settings.clipboardLimit)
        var unpinnedSeen = 0
        var removed: [ClipboardItem] = []
        items = items.filter { item in
            if item.isPinned { return true }
            unpinnedSeen += 1
            if unpinnedSeen <= limit { return true }
            removed.append(item)
            return false
        }
        removed.forEach(deleteImage)
    }

    // MARK: - Aktionen

    /// Sortiert: angeheftete zuerst, dann nach Datum.
    var sortedItems: [ClipboardItem] {
        items.filter(\.isPinned) + items.filter { !$0.isPinned }
    }

    func copy(_ item: ClipboardItem) {
        pasteboard.clearContents()
        switch item.kind {
        case .text:
            pasteboard.setString(item.text ?? "", forType: .string)
        case .link:
            if let url = item.linkURL {
                pasteboard.writeObjects([url as NSURL])
            }
            pasteboard.setString(item.text ?? "", forType: .string)
        case .image:
            if let url = item.imageURL, let image = NSImage(contentsOf: url) {
                pasteboard.writeObjects([image])
            }
        case .files:
            pasteboard.writeObjects(item.fileURLs.map { $0 as NSURL })
        }
        // Eigene Änderung nicht erneut als neuen Eintrag aufnehmen, aber nach oben holen.
        lastChangeCount = pasteboard.changeCount
        if let index = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: index)
            moved.date = Date()
            items.insert(moved, at: 0)
            persist()
        }
        showCopiedFeedback(for: item.id)
    }

    private func showCopiedFeedback(for id: UUID) {
        lastCopiedID = id
        feedbackReset?.cancel()
        let work = DispatchWorkItem { [weak self] in self?.lastCopiedID = nil }
        feedbackReset = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2, execute: work)
    }

    func togglePin(_ item: ClipboardItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].isPinned.toggle()
        enforceLimit()
        persist()
    }

    func delete(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
        deleteImage(item)
        persist()
    }

    /// Leert den Verlauf; angeheftete Einträge bleiben, außer `includingPinned`.
    func clear(includingPinned: Bool = false) {
        let removed = items.filter { includingPinned || !$0.isPinned }
        items.removeAll { includingPinned || !$0.isPinned }
        removed.forEach(deleteImage)
        persist()
    }

    /// Inhalt zum Herausziehen per Drag & Drop.
    func itemProvider(for item: ClipboardItem) -> NSItemProvider {
        switch item.kind {
        case .text:
            return NSItemProvider(object: (item.text ?? "") as NSString)
        case .link:
            if let url = item.linkURL { return NSItemProvider(object: url as NSURL) }
            return NSItemProvider(object: (item.text ?? "") as NSString)
        case .image:
            if let url = item.imageURL, let provider = NSItemProvider(contentsOf: url) { return provider }
            return NSItemProvider()
        case .files:
            if let url = item.fileURLs.first, let provider = NSItemProvider(contentsOf: url) { return provider }
            return NSItemProvider()
        }
    }

    private func deleteImage(_ item: ClipboardItem) {
        guard let url = item.imageURL else { return }
        // Gleiches Bild kann nur einmal vorkommen (Fingerabdruck), daher direkt löschen.
        try? FileManager.default.removeItem(at: url)
    }

    #if DEBUG
    func debugAddSamples() {
        guard items.isEmpty else { return }
        insert(kind: .text, text: "Meeting-Notizen: Release am Freitag, vorher QA-Runde und Changelog aktualisieren.",
               imageFileName: nil, filePaths: nil, source: nil, fingerprint: "t:sample1")
        insert(kind: .link, text: "https://github.com/ungive/mediaremote-adapter",
               imageFileName: nil, filePaths: nil, source: nil, fingerprint: "t:sample2")
        insert(kind: .files, text: nil, imageFileName: nil, filePaths: ["/etc/hosts"], source: nil, fingerprint: "f:sample3")
        insert(kind: .text, text: "brew install --cask notchisland", imageFileName: nil, filePaths: nil,
               source: nil, fingerprint: "t:sample4")
        if let pinned = items.last { togglePin(pinned) }
    }
    #endif

    // MARK: - Persistenz

    private func load() {
        guard let data = try? Data(contentsOf: AppPaths.clipboardIndexFile) else { return }
        do {
            items = try JSONDecoder().decode([ClipboardItem].self, from: data)
        } catch {
            Log.clipboard.error("Clipboard history unreadable: \(error.localizedDescription, privacy: .public)")
        }
    }

    private func persist() {
        do {
            let data = try JSONEncoder().encode(items)
            try data.write(to: AppPaths.clipboardIndexFile, options: .atomic)
        } catch {
            Log.clipboard.error("Saving clipboard history failed: \(error.localizedDescription, privacy: .public)")
        }
    }
}
